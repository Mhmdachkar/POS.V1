  from public.sales
  where customer_id = any(v_cust)
     or id in (select sale_id from public.sale_items where product_id = any(v_prod));

  select coalesce(array_agg(id), array[]::uuid[]) into v_ret
  from public.sale_returns where sale_id = any(v_sale);

  select coalesce(array_agg(id), array[]::uuid[]) into v_shift
  from public.shifts
  where cashier_id in (select id from public.staff where username like 'phase11_test_%' or full_name like 'PHASE11_TEST_%');

  delete from public.sale_return_items where return_id = any(v_ret);
  delete from public.sale_returns where id = any(v_ret);
  delete from public.payments where sale_id = any(v_sale) or customer_id = any(v_cust);
  delete from public.inventory_transactions where product_id = any(v_prod);
  delete from public.stock_entries where product_id = any(v_prod);
  delete from public.sale_items where sale_id = any(v_sale);
  delete from public.sales where id = any(v_sale);
  delete from public.shifts where id = any(v_shift);
  delete from public.product_units where product_id = any(v_prod);
  delete from public.products where id = any(v_prod);
  delete from public.customers where id = any(v_cust);

  select coalesce(array_agg(id), array[]::uuid[]) into v_staff
  from public.staff where username like 'phase11_test_%' or full_name like 'PHASE11_TEST_%';
  delete from public.audit_log
  where actor_id = any(v_staff)
     or entity_id = any(v_staff);
  delete from public.staff where id = any(v_staff);
  delete from auth.identities
    where user_id = any(v_staff)
       or provider_id like 'phase11_test_%@vhm-pos.internal';
  delete from auth.users where id = any(v_staff)
     or email like 'phase11_test_%@vhm-pos.internal';

  select coalesce(array_agg(id), array[]::uuid[]) into v_cat
  from public.categories where name like 'PHASE11_TEST_%';
  delete from public.categories where id = any(v_cat);

  select coalesce(array_agg(id), array[]::uuid[]) into v_depot
  from public.depots where name like 'PHASE11_TEST_%' or code like 'P11%';
  delete from public.audit_log where depot_id = any(v_depot);
  delete from public.depots where id = any(v_depot);

  delete from public.audit_log
  where entity_type in ('product', 'category', 'depot', 'business_settings', 'staff')
    and occurred_at > now() - interval '2 hours'
    and (
      (after_value::text like '%PHASE11_TEST%')
      or (before_value::text like '%PHASE11_TEST%')
    );

  -- Never leave seed staff mutated
  update public.staff set role = 'admin', depot_id = null, is_active = true, deactivated_at = null
  where id = '00000000-0000-0000-0000-000000000001';
  update public.staff set role = 'cashier', depot_id = '00000000-0000-0000-0001-000000000001',
         is_active = true, deactivated_at = null
  where id = '00000000-0000-0000-0000-000000000002';
  update public.staff set role = 'depot_staff', depot_id = '00000000-0000-0000-0001-000000000001',
         is_active = true, deactivated_at = null
  where id = '00000000-0000-0000-0000-000000000003';

  select * into v_snap from public._phase11_settings_snapshot limit 1;
  if v_snap.business_name is not null then
    alter table public.business_settings disable trigger business_settings_set_updated_at;
    update public.business_settings
    set business_name   = v_snap.business_name,
        logo_url        = v_snap.logo_url,
        cfa_to_usd_rate = v_snap.cfa_to_usd_rate,
        rate_updated_at = v_snap.rate_updated_at,
        rate_updated_by = v_snap.rate_updated_by,
        updated_at      = v_snap.updated_at
    where id = true;
    alter table public.business_settings enable trigger business_settings_set_updated_at;
  end if;

  select bool_and(p.current_stock_pieces = s.qty) into v_water_ok
  from public._phase11_seed_stock s
  join public.products p on p.id = s.product_id;
  insert into public._phase11_results (test, expected, actual, status)
  values (
    'seed_stock_unchanged',
    'true',
    coalesce(v_water_ok::text, 'null'),
    case when coalesce(v_water_ok, false) then 'PASS' else 'FAIL' end
  );
end;
$$;

select test, expected, actual, status from public._phase11_results order by seq;
select
  count(*) filter (where status = 'PASS') as passed,
  count(*) filter (where status = 'FAIL') as failed,
  count(*) filter (where status = 'SKIP') as skipped
from public._phase11_results;

drop table if exists public._phase11_results;
drop table if exists public._phase11_settings_snapshot;
drop table if exists public._phase11_seed_stock;
