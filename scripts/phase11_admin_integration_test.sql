from public.products
where id in (
  '00000000-0000-0000-0003-000000000001',
  '00000000-0000-0000-0003-000000000002',
  '00000000-0000-0000-0003-000000000003'
);

create or replace function pg_temp.p11_rec(p_test text, p_expected text, p_actual text, p_ok boolean)
returns void language plpgsql as $$
begin
  insert into public._phase11_results (test, expected, actual, status)
  values (p_test, p_expected, p_actual, case when p_ok then 'PASS' else 'FAIL' end);
end;
$$;

create or replace function pg_temp.p11_skip(p_test text, p_expected text, p_actual text)
returns void language plpgsql as $$
begin
  insert into public._phase11_results (test, expected, actual, status)
  values (p_test, p_expected, p_actual, 'SKIP');
end;
$$;

create or replace function pg_temp.p11_gate()
returns text language sql stable as $$
  select token from private.staff_rpc_gate where id = true
$$;

create or replace function pg_temp.p11_jwt(p_uid uuid)
returns void language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p11_err_code(p_sqlerrm text)
returns text language plpgsql as $$
declare v jsonb;
begin
  begin
    v := p_sqlerrm::jsonb;
    return v->>'code';
  exception when others then
    if p_sqlerrm like '%LAST_ADMIN_REQUIRED%' then return 'LAST_ADMIN_REQUIRED'; end if;
    if p_sqlerrm like '%STAFF_ROLE_SLOT_TAKEN%' then return 'STAFF_ROLE_SLOT_TAKEN'; end if;
    if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
    if p_sqlerrm like '%CANNOT_DEACTIVATE_SELF%' then return 'CANNOT_DEACTIVATE_SELF'; end if;
    if p_sqlerrm like '%STAFF_HAS_OPEN_SHIFT%' then return 'STAFF_HAS_OPEN_SHIFT'; end if;
    if p_sqlerrm like '%DEPOT_HAS_ACTIVE_STAFF%' then return 'DEPOT_HAS_ACTIVE_STAFF'; end if;
    if p_sqlerrm like '%CATEGORY_HAS_ACTIVE_PRODUCTS%' then return 'CATEGORY_HAS_ACTIVE_PRODUCTS'; end if;
    if p_sqlerrm like '%CATEGORY_HAS_ACTIVE_CHILDREN%' then return 'CATEGORY_HAS_ACTIVE_CHILDREN'; end if;
    if p_sqlerrm like '%PRODUCT_IN_PENDING_TRANSFER%' then return 'PRODUCT_IN_PENDING_TRANSFER'; end if;
    if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
    if p_sqlerrm like '%DUPLICATE_PRODUCT_NAME%' then return 'DUPLICATE_PRODUCT_NAME'; end if;
    return left(p_sqlerrm, 180);
  end;
end;
$$;

create or replace function pg_temp.p11_mk_auth(p_id uuid, p_email text)
returns void language plpgsql as $$
begin
  insert into auth.users (
    id, instance_id, aud, role,
    email, encrypted_password,
    email_confirmed_at,
    raw_app_meta_data, raw_user_meta_data,
    created_at, updated_at,
    confirmation_token, recovery_token,
    email_change_token_new, email_change,
    is_sso_user
  ) values (
    p_id, '00000000-0000-0000-0000-000000000000',
    'authenticated', 'authenticated',
    p_email,
    crypt('Phase11Test!', gen_salt('bf')),
    now(),
    '{"provider":"email","providers":["email"]}'::jsonb,
    '{}'::jsonb,
    now(), now(),
    p_id::text, '', p_id::text, '',
    false
  )
  on conflict (id) do nothing;

  insert into auth.identities (
    id, user_id, provider_id, provider, identity_data,
    last_sign_in_at, created_at, updated_at
  ) values (
    p_id, p_id, p_email, 'email',
    jsonb_build_object('sub', p_id, 'email', p_email),
    now(), now(), now()
  )
  on conflict (id) do nothing;
end;
$$;

