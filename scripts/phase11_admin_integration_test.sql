-- Durable tables: Management API auto-commits each statement, so a
-- failed test DO would otherwise roll back a TEMP snapshot and let
-- cleanup write nulls into business_settings.
drop table if exists public._phase11_results;
create table public._phase11_results (
  seq      int generated by default as identity,
  test     text not null,
  expected text not null,
  actual   text not null,
  status   text not null check (status in ('PASS', 'FAIL', 'SKIP'))
);

drop table if exists public._phase11_settings_snapshot;
create table public._phase11_settings_snapshot as
select business_name, logo_url, cfa_to_usd_rate, rate_updated_at, rate_updated_by, updated_at
from public.business_settings
where id = true;

