create or replace function pg_temp.p9_rec(
  p_test     text,
  p_expected text,
  p_actual   text,
  p_ok       boolean
) returns void
language plpgsql as $$
begin
  insert into phase9_transfer_results (test, expected, actual, status)
  values (
    p_test, p_expected, p_actual,
    case when p_ok then 'PASS' else 'FAIL' end
