    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('unauthorized cashier draft', 'UNAUTHORIZED', v_code, v_code = 'UNAUTHORIZED');

  v_code := 'NO_ERROR';
  begin
    perform public.complete_transfer(v_tr);
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec(
    'unauthorized cashier complete',
    'UNAUTHORIZED or TRANSFER_ALREADY_COMPLETED',
    v_code,
    v_code in ('UNAUTHORIZED', 'TRANSFER_ALREADY_COMPLETED')
  );

  -- ── double complete ──────────────────────────────────────────
  perform pg_temp.p9_jwt(admin_id);
  v_code := 'NO_ERROR';
  begin
    perform public.complete_transfer(v_tr);
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('double complete', 'TRANSFER_ALREADY_COMPLETED', v_code, v_code = 'TRANSFER_ALREADY_COMPLETED');

  -- ── cancel pending ───────────────────────────────────────────
  v_result := public.create_transfer_draft(
    depot_a_id, depot_b_id,
    jsonb_build_array(jsonb_build_object(
      'from_product_id', src_cancel, 'to_product_id', dst_cancel,
      'unit_level', 0, 'quantity_in_unit', 2
    )),
    'PHASE9_TEST_CANCEL'
  );
  v_tr_cancel := (v_result->>'transfer_id')::uuid;
  select current_stock_pieces into v_stock_src from public.products where id = src_cancel;
  select current_stock_pieces into v_stock_dst from public.products where id = dst_cancel;

  v_result := public.cancel_transfer(v_tr_cancel, 'PHASE9_TEST_REASON');
  select status, cancel_reason into v_status, v_reason
  from public.stock_transfers where id = v_tr_cancel;

  perform pg_temp.p9_rec(
    'cancel pending',
    'cancelled + reason stored',
    format('%s reason=%s', v_status, v_reason),
    v_status = 'cancelled'
      and v_reason = 'PHASE9_TEST_REASON'
      and (select cancelled_by from public.stock_transfers where id = v_tr_cancel) = admin_id
      and (select cancelled_at from public.stock_transfers where id = v_tr_cancel) is not null
  );

  perform pg_temp.p9_rec(
    'cancel no stock change',
    format('src=%s dest=%s', v_stock_src, v_stock_dst),
    format('src=%s dest=%s',
      (select current_stock_pieces from public.products where id = src_cancel),
      (select current_stock_pieces from public.products where id = dst_cancel)),
    (select current_stock_pieces from public.products where id = src_cancel) = v_stock_src
      and (select current_stock_pieces from public.products where id = dst_cancel) = v_stock_dst
  );

  select count(*) into v_cnt
  from public.inventory_transactions where reference_id = v_tr_cancel;
  perform pg_temp.p9_rec('cancel no ledger', '0', v_cnt::text, v_cnt = 0);

  -- ── cancel completed ─────────────────────────────────────────
  v_code := 'NO_ERROR';
  begin
    perform public.cancel_transfer(v_tr, 'nope');
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('cancel completed', 'TRANSFER_ALREADY_COMPLETED', v_code, v_code = 'TRANSFER_ALREADY_COMPLETED');

  -- ── cancel already cancelled ─────────────────────────────────
  v_code := 'NO_ERROR';
  begin
    perform public.cancel_transfer(v_tr_cancel, 'again');
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('cancel already cancelled', 'TRANSFER_CANCELLED', v_code, v_code = 'TRANSFER_CANCELLED');

  -- ── cancel wrong depot ───────────────────────────────────────
  v_result := public.create_transfer_draft(
    depot_a_id, depot_b_id,
    jsonb_build_array(jsonb_build_object(
      'from_product_id', src_cancel, 'to_product_id', dst_cancel,
      'unit_level', 0, 'quantity_in_unit', 1
    )),
    'PHASE9_TEST_CANCEL_SCOPE'
  );
  -- Pretend from_depot is B by creating as admin then calling as depot staff
  -- depot_staff owns A, so a transfer from A is allowed. Create from B via admin:
  -- Instead: complete isolation — depot_staff cancelling a transfer they do not own
  -- requires from_depot = B. Create as admin from A is ownable. Use a header
  -- created as admin from A — depot_staff CAN cancel that. So create from B:
  delete from public.stock_transfer_items where transfer_id = (v_result->>'transfer_id')::uuid;
  delete from public.stock_transfers where id = (v_result->>'transfer_id')::uuid;

  v_result := public.create_transfer_draft(
    depot_b_id, depot_a_id,
    jsonb_build_array(jsonb_build_object(
      'from_product_id', dst_ok, 'to_product_id', src_ok,
      'unit_level', 0, 'quantity_in_unit', 1
    )),
    'PHASE9_TEST_FROM_B'
  );
  perform pg_temp.p9_jwt(depot_staff_id);
  v_code := 'NO_ERROR';
  begin
    perform public.cancel_transfer((v_result->>'transfer_id')::uuid, 'nope');
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('cancel wrong depot', 'INVALID_DEPOT', v_code, v_code = 'INVALID_DEPOT');

  -- ── cancel unauthorized ──────────────────────────────────────
  perform pg_temp.p9_jwt(cashier_id);
  v_code := 'NO_ERROR';
  begin
    perform public.cancel_transfer((v_result->>'transfer_id')::uuid, 'nope');
  exception when others then
    v_code := pg_temp.p9_err_code(sqlerrm);
  end;
  perform pg_temp.p9_rec('cancel unauthorized', 'UNAUTHORIZED', v_code, v_code = 'UNAUTHORIZED');

  -- ── audit correctness ────────────────────────────────────────
  perform pg_temp.p9_jwt(admin_id);
  select count(*) into v_cnt from public.audit_log
   where action = 'create_transfer_draft' and entity_id = v_tr;
  select count(*) into v_cnt2 from public.audit_log
   where action = 'complete_transfer' and entity_id = v_tr;
  perform pg_temp.p9_rec(
    'audit create+complete',
    '1 + 1',
    format('create=%s complete=%s', v_cnt, v_cnt2),
    v_cnt = 1 and v_cnt2 = 1
  );

  select count(*) into v_cnt from public.audit_log
   where action = 'cancel_transfer' and entity_id = v_tr_cancel
     and after_value->>'cancel_reason' = 'PHASE9_TEST_REASON';
  perform pg_temp.p9_rec('audit cancel', '1', v_cnt::text, v_cnt = 1);

  -- ── concurrency placeholders ─────────────────────────────────
  perform pg_temp.p9_skip(
    'CONCURRENCY TEST A same transfer',
    'one success + TRANSFER_ALREADY_COMPLETED',
    'SQL editor is a single session — verify separately or UNVERIFIED'
  );
  perform pg_temp.p9_skip(
    'CONCURRENCY TEST B competing stock',
    'one success + INSUFFICIENT_STOCK',
    'SQL editor is a single session — verify separately or UNVERIFIED'
  );
  perform pg_temp.p9_skip(
    'CANCEL CONCURRENCY',
    'one success + TRANSFER_CANCELLED',
    'SQL editor is a single session — verify separately or UNVERIFIED'
  );

  -- ── isolated cleanup (keep BROWSER products) ─────────────────
  perform set_config('request.jwt.claims', '{}', false);
  perform set_config('request.jwt.sub', '', false);

  delete from public.stock_transfer_items
   where from_product_id in (src_ok, src_inact, src_low, src_deact, src_cancel, dst_ok)
      or to_product_id in (dst_ok, dst_inact, dst_low, dst_deact, dst_cancel, src_ok);
  delete from public.inventory_transactions
   where product_id in (src_ok, dst_ok, src_inact, dst_inact, src_low, dst_low, src_deact, dst_deact, src_cancel, dst_cancel);
  delete from public.audit_log
   where entity_id in (select id from public.stock_transfers where note like 'PHASE9_TEST_%');
  delete from public.stock_transfers where note like 'PHASE9_TEST_%';
  delete from public.product_units
   where product_id in (src_ok, dst_ok, src_inact, dst_inact, src_low, dst_low, src_deact, dst_deact, src_cancel, dst_cancel);
  delete from public.products
   where id in (src_ok, dst_ok, src_inact, dst_inact, src_low, dst_low, src_deact, dst_deact, src_cancel, dst_cancel);

  perform pg_temp.p9_rec(
    'cleanup isolated leftovers',
    '0 isolated PHASE9 products',
    (select count(*)::text from public.products
      where name like 'PHASE9_TEST_%' and name not like 'PHASE9_TEST_BROWSER_%'),
    not exists (
      select 1 from public.products
      where name like 'PHASE9_TEST_%' and name not like 'PHASE9_TEST_BROWSER_%'
    )
  );

  perform pg_temp.p9_rec(
    'seed Water/Soda/Rice unchanged',
    format('w=%s s=%s r=%s wb=%s', seed_water, seed_soda, seed_rice, seed_water_b),
    format('w=%s s=%s r=%s wb=%s',
      (select current_stock_pieces from public.products where id = water_id),
      (select current_stock_pieces from public.products where id = soda_id),
      (select current_stock_pieces from public.products where id = rice_id),
      (select current_stock_pieces from public.products where id = water_b_id)),
    (select current_stock_pieces from public.products where id = water_id) = seed_water
      and (select current_stock_pieces from public.products where id = soda_id) = seed_soda
      and (select current_stock_pieces from public.products where id = rice_id) = seed_rice
      and (select current_stock_pieces from public.products where id = water_b_id) = seed_water_b
  );

  perform pg_temp.p9_rec(
    'browser fixtures left',
    'PHASE9_TEST_BROWSER_SRC + DST',
    (select string_agg(name, ',') from public.products where name like 'PHASE9_TEST_BROWSER_%'),
    exists (select 1 from public.products where id = src_br)
      and exists (select 1 from public.products where id = dst_br)
  );
end;
