    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('duplicate sale_item_id return rejected', 'INVALID_INPUT', v_code, v_code = 'INVALID_INPUT');
  perform pg_temp.p17b_assert_stock(prod_src, 80, 'duplicate return did not restore stock');

  -- ── partial return 4 ────────────────────────────────────────
  v_result := public.process_return(
    p_sale_id := v_sale,
    p_items := jsonb_build_array(
      jsonb_build_object('sale_item_id', v_item, 'quantity_in_unit', 4)
    ),
    p_cash_refund_cfa := 2000::numeric
  );
  perform pg_temp.p17b_assert_stock(prod_src, 84, 'after partial return 4');
  perform pg_temp.p17b_rec(
    'partial return status',
    'partially_returned',
    v_result->>'new_sale_status',
    v_result->>'new_sale_status' = 'partially_returned'
  );

  v_code := 'NO_ERROR';
  begin
    perform public.process_return(
      p_sale_id := v_sale,
      p_items := jsonb_build_array(
        jsonb_build_object('sale_item_id', v_item, 'quantity_in_unit', 7)
      ),
      p_cash_refund_cfa := 3500::numeric
    );
  exception when sqlstate 'P0001' then
    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('over-return rejected', 'RETURN_QTY_EXCEEDED', v_code, v_code = 'RETURN_QTY_EXCEEDED');
  perform pg_temp.p17b_assert_stock(prod_src, 84, 'over-return did not mutate stock');

