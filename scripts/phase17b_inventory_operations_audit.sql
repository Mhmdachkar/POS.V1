  water_id       constant uuid := '00000000-0000-0000-0003-000000000001';
  photo          constant text := 'https://images.unsplash.com/photo-1559839914-17aae19cec71?auto=format&fit=crop&w=800&h=800&q=80';

  prod_src       constant uuid := 'a17b0000-0017-4e17-8000-000000000001';
  prod_dst       constant uuid := 'a17b0000-0017-4e17-8000-000000000002';
  prod_cancel_s  constant uuid := 'a17b0000-0017-4e17-8000-000000000003';
  prod_cancel_d  constant uuid := 'a17b0000-0017-4e17-8000-000000000004';
  prod_foreign   constant uuid := 'a17b0000-0017-4e17-8000-000000000005';
  prod_br_src    constant uuid := 'a17b0000-0017-4e17-8000-000000000011';
  prod_br_dst    constant uuid := 'a17b0000-0017-4e17-8000-000000000012';

