    product_id, unit_level, unit_name, conversion_to_base, cost_price_cfa, selling_price_cfa
  ) values
    (prod_src, 0, 'Piece', 1, 200, 500),
    (prod_dst, 0, 'Piece', 1, 200, 500),
    (prod_cancel_s, 0, 'Piece', 1, 200, 500),
    (prod_cancel_d, 0, 'Piece', 1, 200, 500),
    (prod_foreign, 0, 'Piece', 1, 200, 500),
    (prod_br_src, 0, 'Piece', 1, 200, 500),
    (prod_br_dst, 0, 'Piece', 1, 200, 500)
  on conflict (product_id, unit_level) do update
    set selling_price_cfa = excluded.selling_price_cfa;

