-- ================================================================
-- PHASE 17B — INVENTORY OPERATIONS AUDIT
-- TEST-ONLY ARTIFACT. NOT A MIGRATION. NOT PRODUCTION CODE.
-- ================================================================
--
-- Purpose: live-verify that every stock-changing workflow keeps
--   products.current_stock_pieces
--   = SUM(inventory_transactions.quantity_pieces)
--   = independently computed expected stock
-- on dedicated PHASE17B_TEST_* fixtures.
--
-- Lifecycle on one source SKU:
--   start 0 → restock 100 → adjustments → sale 10 → return 4
--   → transfer 10 to destination depot
--
-- DO NOT run: rpc_transactions.test.sql, reset_dev_baseline.sql,
--             supabase db reset
-- DO NOT wipe seed or disable RLS.
--
-- Run in the hosted TEST project SQL editor as the postgres role.
--
-- Fixture namespace: a17b0000-0017-4e17-*
-- Isolated rows are removed at the end.
-- PHASE17B_TEST_BROWSER_* products are LEFT for the UI pass.
--
-- CONCURRENCY: this SQL editor session cannot open two independent
-- client connections. Dual-session stock races are SKIP here;
-- run scripts/phase17b_concurrent_adjust.mjs against the hosted
-- project for a real FOR UPDATE race.
-- ================================================================

create temporary table if not exists phase17b_inv_results (
  seq      int generated by default as identity,
  test     text not null,
  expected text not null,
  actual   text not null,
  status   text not null check (status in ('PASS', 'FAIL', 'SKIP'))
);

create or replace function pg_temp.p17b_rec(
  p_test     text,
  p_expected text,
  p_actual   text,
  p_ok       boolean
) returns void
language plpgsql as $$
begin
  insert into phase17b_inv_results (test, expected, actual, status)
  values (
    p_test, p_expected, p_actual,
    case when p_ok then 'PASS' else 'FAIL' end
  );
end;
$$;

create or replace function pg_temp.p17b_skip(
  p_test     text,
  p_expected text,
  p_actual   text
) returns void
language plpgsql as $$
begin
  insert into phase17b_inv_results (test, expected, actual, status)
  values (p_test, p_expected, p_actual, 'SKIP');
end;
$$;

create or replace function pg_temp.p17b_jwt(p_uid uuid)
returns void
language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p17b_err_code(p_sqlerrm text)
returns text
language plpgsql as $$
begin
  if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
  if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
  if p_sqlerrm like '%INVALID_INPUT%' then return 'INVALID_INPUT'; end if;
  if p_sqlerrm like '%INVALID_QUANTITY%' then return 'INVALID_QUANTITY'; end if;
  if p_sqlerrm like '%ADJUSTMENT_NEGATIVE_RESULT%' then return 'ADJUSTMENT_NEGATIVE_RESULT'; end if;
  if p_sqlerrm like '%INSUFFICIENT_STOCK%' then return 'INSUFFICIENT_STOCK'; end if;
  if p_sqlerrm like '%RETURN_QTY_EXCEEDED%' then return 'RETURN_QTY_EXCEEDED'; end if;
  return p_sqlerrm;
end;
$$;

-- Hosted SQL editor types unadorned integers as int4. That cannot
-- resolve restock_product(uuid, smallint, numeric, text). Named
-- args plus explicit casts match the live signature exactly.
create or replace function pg_temp.p17b_restock(
  p_product_id uuid,
  p_qty        numeric,
  p_note       text
) returns jsonb
language plpgsql as $$
begin
  return public.restock_product(
    p_product_id       := p_product_id,
    p_unit_level       := 0::smallint,
    p_quantity_in_unit := p_qty,
    p_note             := p_note
  );
end;
$$;

create or replace function pg_temp.p17b_adjust(
  p_product_id uuid,
  p_type       text,
  p_qty        numeric,
  p_reason     text
) returns jsonb
language plpgsql as $$
begin
  return public.adjust_inventory(
    p_product_id      := p_product_id,
    p_adjustment_type := p_type,
    p_quantity_pieces := p_qty,
    p_reason          := p_reason
  );
end;
$$;

create or replace function pg_temp.p17b_ledger(p_product_id uuid)
returns numeric
language sql as $$
  select coalesce(sum(quantity_pieces), 0)
  from public.inventory_transactions
  where product_id = p_product_id;
$$;

create or replace function pg_temp.p17b_assert_stock(
  p_product_id uuid,
  p_expected   numeric,
  p_label      text
) returns void
language plpgsql as $$
declare
  v_stock  numeric;
  v_ledger numeric;
begin
  select current_stock_pieces into v_stock
  from public.products where id = p_product_id;
  v_ledger := pg_temp.p17b_ledger(p_product_id);
  perform pg_temp.p17b_rec(
    p_label,
    format('stock=ledger=%s', p_expected),
    format('stock=%s ledger=%s', v_stock, v_ledger),
    v_stock is not distinct from p_expected
      and v_ledger is not distinct from p_expected
  );
end;
$$;

create or replace function pg_temp.p17b_cleanup_isolated()
returns void
language plpgsql as $$
declare
  v_prod uuid[];
  v_sale uuid[];
  v_ret  uuid[];
  v_tr   uuid[];
begin
  perform set_config('request.jwt.claims', '{}', false);
  perform set_config('request.jwt.sub', '', false);

  select coalesce(array_agg(id), array[]::uuid[]) into v_prod
  from public.products
  where name like 'PHASE17B_TEST_%'
    and name not like 'PHASE17B_TEST_BROWSER_%';

  select coalesce(array_agg(id), array[]::uuid[]) into v_sale
  from public.sales
  where id in (select sale_id from public.sale_items where product_id = any(v_prod));

  select coalesce(array_agg(id), array[]::uuid[]) into v_ret
  from public.sale_returns where sale_id = any(v_sale);

  select coalesce(array_agg(id), array[]::uuid[]) into v_tr
  from public.stock_transfers
  where note like 'PHASE17B_TEST_%'
     or id in (
       select transfer_id from public.stock_transfer_items
       where from_product_id = any(v_prod) or to_product_id = any(v_prod)
     );

  delete from public.sale_return_items where return_id = any(v_ret);
  delete from public.payments where sale_id = any(v_sale);
  delete from public.sale_returns where id = any(v_ret);
  delete from public.sale_items where sale_id = any(v_sale);
  delete from public.stock_transfer_items where transfer_id = any(v_tr);
  delete from public.inventory_transactions
   where product_id = any(v_prod) or reference_id = any(v_tr) or reference_id = any(v_sale);
  delete from public.inventory_adjustments where product_id = any(v_prod);
  delete from public.stock_entries where product_id = any(v_prod);
  delete from public.sales where id = any(v_sale);
  delete from public.stock_transfers where id = any(v_tr);
  -- Never cast after_value fields to uuid: live audit rows can contain
  -- non-uuid JSON and that abort would hide every real assertion.
  delete from public.audit_log
   where entity_id = any(v_prod)
      or entity_id = any(v_sale)
      or entity_id = any(v_ret)
      or entity_id = any(v_tr)
      or after_value->>'product_id' = any (v_prod::text[])
      or after_value::text like '%PHASE17B_TEST_%'
      or before_value::text like '%PHASE17B_TEST_%';
  delete from public.product_units where product_id = any(v_prod);
  delete from public.products where id = any(v_prod);
end;
$$;

-- Browser fixtures are left behind. If they have stock but no ledger
-- (the previous suite died on a NOT NULL reference_id insert), write a
-- matching RESTOCK row so leftover SKUs stay internally consistent.
create or replace function pg_temp.p17b_ensure_browser_baseline(
  p_product_id uuid,
  p_target     numeric,
  p_admin_id   uuid
) returns void
language plpgsql as $$
declare
  v_depot uuid;
  v_entry uuid;
begin
  if pg_temp.p17b_ledger(p_product_id) <> 0 then
    return;
  end if;

  update public.products
     set current_stock_pieces = p_target
   where id = p_product_id
  returning depot_id into v_depot;

  insert into public.stock_entries (
    product_id, depot_id, unit_level,
    quantity_in_unit, quantity_pieces,
    note, entered_by
  ) values (
    p_product_id, v_depot, 0,
    p_target, p_target,
    'PHASE17B_TEST_BROWSER_BASELINE', p_admin_id
  )
  returning id into v_entry;

  insert into public.inventory_transactions (
    depot_id, product_id, quantity_pieces,
    transaction_type, reference_type, reference_id,
    created_by, metadata
  ) values (
    v_depot, p_product_id, p_target,
    'RESTOCK', 'stock_entry', v_entry,
    p_admin_id,
    jsonb_build_object('note', 'PHASE17B_TEST_BROWSER_BASELINE')
  );
end;
$$;

do $phase17b$
declare
