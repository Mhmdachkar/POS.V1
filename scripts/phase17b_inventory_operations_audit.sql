    'PHASE17B_TEST_MOVE'
  );
  v_tr := (v_result->>'transfer_id')::uuid;
  perform pg_temp.p17b_assert_stock(prod_src, 84, 'draft transfer source unchanged');
  perform pg_temp.p17b_assert_stock(prod_dst, 0, 'draft transfer dest unchanged');

  perform public.complete_transfer(v_tr);
  perform pg_temp.p17b_assert_stock(prod_src, 74, 'after transfer source -10');
  perform pg_temp.p17b_assert_stock(prod_dst, 10, 'after transfer dest +10');
  perform pg_temp.p17b_rec(
    'transfer ledger pair',
    'OUT -10 and IN +10',
    format(
      'out=%s in=%s',
      (select quantity_pieces from public.inventory_transactions
       where reference_id = v_tr and transaction_type = 'TRANSFER_OUT'),
      (select quantity_pieces from public.inventory_transactions
       where reference_id = v_tr and transaction_type = 'TRANSFER_IN')
    ),
    exists (
      select 1 from public.inventory_transactions
      where reference_id = v_tr and transaction_type = 'TRANSFER_OUT' and quantity_pieces = -10
    ) and exists (
      select 1 from public.inventory_transactions
      where reference_id = v_tr and transaction_type = 'TRANSFER_IN' and quantity_pieces = 10
    )
  );

  v_code := 'NO_ERROR';
  begin
    perform public.complete_transfer(v_tr);
  exception when sqlstate 'P0001' then
    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('double complete rejected', 'not NO_ERROR', v_code, v_code <> 'NO_ERROR');
  perform pg_temp.p17b_assert_stock(prod_src, 74, 'double complete did not move stock again');

  -- ── cancel transfer does not move stock ─────────────────────
  v_result := public.create_transfer_draft(
    depot_a_id, depot_b_id,
    jsonb_build_array(jsonb_build_object(
      'from_product_id', prod_cancel_s, 'to_product_id', prod_cancel_d,
      'unit_level', 0, 'quantity_in_unit', 5
    )),
    'PHASE17B_TEST_CANCEL'
  );
  v_tr_cancel := (v_result->>'transfer_id')::uuid;
  perform public.cancel_transfer(v_tr_cancel, 'PHASE17B_TEST_CANCEL_REASON');
