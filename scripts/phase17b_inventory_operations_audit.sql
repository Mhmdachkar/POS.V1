    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('cashier restock rejected', 'UNAUTHORIZED', v_code, v_code = 'UNAUTHORIZED');
  perform pg_temp.p17b_assert_stock(prod_src, 0, 'cashier restock did not mutate stock');

  -- ── depot_staff cannot restock another depot ────────────────
  perform pg_temp.p17b_jwt(depot_staff_id);
  v_code := 'NO_ERROR';
  begin
    perform pg_temp.p17b_restock(prod_foreign, 1::numeric, 'PHASE17B_TEST_CROSS');
  exception when sqlstate 'P0001' then
    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('depot_staff foreign restock rejected', 'INVALID_DEPOT', v_code, v_code = 'INVALID_DEPOT');

