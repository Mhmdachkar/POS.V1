  perform pg_temp.p17b_assert_stock(prod_src, 95, 'after DAMAGE -5');

  perform pg_temp.p17b_adjust(prod_src, 'LOSS', (-3)::numeric, 'PHASE17B_TEST_LOSS');
  perform pg_temp.p17b_assert_stock(prod_src, 92, 'after LOSS -3');

  perform pg_temp.p17b_adjust(prod_src, 'EXPIRY', (-2)::numeric, 'PHASE17B_TEST_EXPIRY');
  perform pg_temp.p17b_assert_stock(prod_src, 90, 'after EXPIRY -2');

  perform pg_temp.p17b_adjust(prod_src, 'COUNT_CORRECTION', (-4)::numeric, 'PHASE17B_TEST_COUNT_NEG');
  perform pg_temp.p17b_assert_stock(prod_src, 86, 'after COUNT_CORRECTION -4');

  perform pg_temp.p17b_adjust(prod_src, 'COUNT_CORRECTION', 6::numeric, 'PHASE17B_TEST_COUNT_POS');
  perform pg_temp.p17b_assert_stock(prod_src, 92, 'after COUNT_CORRECTION +6');

  perform pg_temp.p17b_adjust(prod_src, 'OTHER', (-2)::numeric, 'PHASE17B_TEST_OTHER');
  perform pg_temp.p17b_assert_stock(prod_src, 90, 'after OTHER -2');

  v_code := 'NO_ERROR';
  begin
    perform pg_temp.p17b_adjust(prod_src, 'DAMAGE', 1::numeric, 'PHASE17B_TEST_BAD_SIGN');
  exception when sqlstate 'P0001' then
    v_code := pg_temp.p17b_err_code(sqlerrm);
  end;
  perform pg_temp.p17b_rec('DAMAGE positive qty rejected', 'INVALID_QUANTITY', v_code, v_code = 'INVALID_QUANTITY');
  perform pg_temp.p17b_assert_stock(prod_src, 90, 'invalid DAMAGE did not mutate stock');

