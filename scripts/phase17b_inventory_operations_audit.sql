  v_result       jsonb;
  v_code         text;
  v_sale         uuid;
  v_item         uuid;
  v_tr           uuid;
  v_tr_cancel    uuid;
  v_stock        numeric;
  v_units        jsonb := jsonb_build_array(jsonb_build_object(
    'unit_level', 0, 'unit_name', 'Piece',
    'conversion_to_base', 1, 'cost_price_cfa', 200, 'selling_price_cfa', 500
  ));
begin
