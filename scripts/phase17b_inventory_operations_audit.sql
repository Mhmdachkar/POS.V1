    'restock RPC pieces',
    '100',
    v_result->>'quantity_pieces',
    (v_result->>'quantity_pieces')::numeric = 100
  );
  perform pg_temp.p17b_assert_stock(prod_src, 100, 'after restock 100');
  perform pg_temp.p17b_rec(
    'restock audit',
    'restock_product present',
    exists (select 1 from public.audit_log where action = 'restock_product' and entity_id = (v_result->>'entry_id')::uuid)::text,
    exists (select 1 from public.audit_log where action = 'restock_product' and entity_id = (v_result->>'entry_id')::uuid)
  );

