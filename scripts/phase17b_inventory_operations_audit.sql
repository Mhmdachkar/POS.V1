    p_product_id          := prod_src,
    p_category_id         := cat_bev_id,
    p_name                := 'PHASE17B_TEST_SRC',
    p_photo_url           := photo,
    p_units               := jsonb_build_array(jsonb_build_object(
      'unit_level', 0, 'unit_name', 'Piece',
      'conversion_to_base', 1, 'cost_price_cfa', 250, 'selling_price_cfa', 600
    )),
    p_track_low_stock     := true,
    p_low_stock_threshold := 5::numeric
  );
  perform pg_temp.p17b_assert_stock(prod_src, 84, 'update_product did not change stock');
  perform pg_temp.p17b_rec(
    'update_product depot_id unchanged',
    depot_a_id::text,
    (select depot_id::text from public.products where id = prod_src),
    (select depot_id from public.products where id = prod_src) = depot_a_id
  );

  -- ── draft transfer does not move stock ──────────────────────
  v_result := public.create_transfer_draft(
    depot_a_id, depot_b_id,
    jsonb_build_array(jsonb_build_object(
      'from_product_id', prod_src, 'to_product_id', prod_dst,
      'unit_level', 0, 'quantity_in_unit', 10
