    id, depot_id, category_id, name, photo_url, current_stock_pieces, is_active
  ) values
    (prod_br_src, depot_a_id, cat_bev_id, 'PHASE17B_TEST_BROWSER_SRC', photo, 40, true),
    (prod_br_dst, depot_b_id, cat_bev_id, 'PHASE17B_TEST_BROWSER_DST', photo, 5, true)
  on conflict (id) do update
    set is_active = true,
        photo_url = excluded.photo_url;

