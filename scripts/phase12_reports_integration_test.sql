create or replace function pg_temp.p12_jwt(p_uid uuid)
returns void language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p12_err_code(p_sqlerrm text)
returns text language plpgsql as $$
declare v jsonb;
begin
  begin
    v := p_sqlerrm::jsonb;
    return v->>'code';
  exception when others then
    if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
    if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
    return left(p_sqlerrm, 180);
  end;
end;
$$;

create or replace function pg_temp.p12_num(p jsonb, p_key text)
returns numeric language sql immutable as $$
  select coalesce((p->>p_key)::numeric, 0)
$$;

create or replace function pg_temp.p12_has(p jsonb, p_arr text, p_field text, p_val text)
returns boolean language sql stable as $$
  select exists (
    select 1 from jsonb_array_elements(coalesce(p->p_arr, '[]'::jsonb)) x
    where x->>p_field = p_val
  )
$$;

create or replace function pg_temp.p12_row_num(p jsonb, p_arr text, p_field text, p_val text, p_num text)
returns numeric language sql stable as $$
  select coalesce((
    select (x->>p_num)::numeric
    from jsonb_array_elements(coalesce(p->p_arr, '[]'::jsonb)) x
    where x->>p_field = p_val
    limit 1
  ), 0)
$$;

