create temporary table if not exists phase8_sales_results (
  seq      int generated by default as identity,
  test     text not null,
  expected text not null,
  actual   text not null,
  status   text not null check (status in ('PASS', 'FAIL', 'SKIP'))
);

create or replace function pg_temp.p8_rec(
  p_test     text,
  p_expected text,
  p_actual   text,
  p_ok       boolean
) returns void
language plpgsql as $$
begin
  insert into phase8_sales_results (test, expected, actual, status)
  values (
    p_test,
    p_expected,
    p_actual,
    case when p_ok then 'PASS' else 'FAIL' end
  );
end;
$$;

create or replace function pg_temp.p8_skip(
  p_test     text,
  p_expected text,
  p_actual   text
) returns void
language plpgsql as $$
begin
  insert into phase8_sales_results (test, expected, actual, status)
  values (p_test, p_expected, p_actual, 'SKIP');
end;
$$;

create or replace function pg_temp.p8_jwt(p_uid uuid)
returns void
language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p8_err_code(p_sqlerrm text)
returns text
language plpgsql as $$
declare
  v jsonb;
begin
  begin
    v := p_sqlerrm::jsonb;
    return v->>'code';
  exception when others then
    if p_sqlerrm like '%SALE_NOT_FOUND%' then return 'SALE_NOT_FOUND'; end if;
    if p_sqlerrm like '%SALE_VOIDED%' then return 'SALE_VOIDED'; end if;
    if p_sqlerrm like '%SALE_FULLY_RETURNED%' then return 'SALE_FULLY_RETURNED'; end if;
    if p_sqlerrm like '%RETURN_QTY_EXCEEDED%' then return 'RETURN_QTY_EXCEEDED'; end if;
    if p_sqlerrm like '%INVALID_AMOUNT%' then return 'INVALID_AMOUNT'; end if;
    if p_sqlerrm like '%INVALID_QUANTITY%' then return 'INVALID_QUANTITY'; end if;
    if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
    if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
    if p_sqlerrm like '%CART_EMPTY%' then return 'CART_EMPTY'; end if;
    if p_sqlerrm like '%CUSTOMER_NOT_FOUND%' then return 'CUSTOMER_NOT_FOUND'; end if;
    if p_sqlerrm like '%CUSTOMER_REQUIRED%' then return 'CUSTOMER_REQUIRED'; end if;
    return p_sqlerrm;
  end;
end;
$$;

-- Removes every PHASE8_TEST_* row (products, customers, sales, ledger, audit).
-- Used on fatal error. The happy-path end of the suite uses isolated cleanup
-- and leaves PHASE8_TEST_BROWSER_* sales for the UI pass.
create or replace function pg_temp.p8_cleanup_all()
returns void
language plpgsql as $$
declare
  v_prod uuid[];
  v_cust uuid[];
  v_sale uuid[];
  v_ret  uuid[];
begin
  perform set_config('request.jwt.claims', '{}', false);
  perform set_config('request.jwt.sub', '', false);

  select coalesce(array_agg(id), array[]::uuid[]) into v_prod
  from public.products where name like 'PHASE8_TEST_%';

  select coalesce(array_agg(id), array[]::uuid[]) into v_cust
  from public.customers where name like 'PHASE8_TEST_%';

  select coalesce(array_agg(id), array[]::uuid[]) into v_sale
  from public.sales
  where customer_id = any(v_cust)
     or id in (select sale_id from public.sale_items where product_id = any(v_prod));

  select coalesce(array_agg(id), array[]::uuid[]) into v_ret
  from public.sale_returns where sale_id = any(v_sale);

  delete from public.sale_return_items where return_id = any(v_ret);
  delete from public.payments
   where sale_id = any(v_sale)
      or customer_id = any(v_cust);
  delete from public.sale_returns where id = any(v_ret);
  delete from public.sale_items where sale_id = any(v_sale);
  delete from public.inventory_transactions where product_id = any(v_prod);
  delete from public.stock_entries where product_id = any(v_prod);
  delete from public.sales where id = any(v_sale);
  delete from public.audit_log
   where entity_id = any(v_sale)
      or entity_id = any(v_ret)
      or entity_id = any(v_cust)
      or entity_id = any(v_prod)
      or entity_id in (select id from public.payments where customer_id = any(v_cust))
      or (after_value->>'sale_id')::uuid = any(v_sale)
      or (after_value->>'product_id')::uuid = any(v_prod)
      or (after_value->>'customer_id')::uuid = any(v_cust);
  delete from public.customers where id = any(v_cust);
  delete from public.product_units where product_id = any(v_prod);
  delete from public.products where id = any(v_prod);
end;
$$;

