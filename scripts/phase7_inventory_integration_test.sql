create temporary table if not exists phase7_inv_results (
  seq      int generated by default as identity,
  test     text not null,
  expected text not null,
  actual   text not null,
  status   text not null check (status in ('PASS', 'FAIL', 'SKIP'))
);

create or replace function pg_temp.p7_rec(
  p_test     text,
  p_expected text,
  p_actual   text,
  p_ok       boolean
) returns void
language plpgsql as $$
begin
  insert into phase7_inv_results (test, expected, actual, status)
  values (
    p_test,
    p_expected,
    p_actual,
    case when p_ok then 'PASS' else 'FAIL' end
  );
end;
$$;

create or replace function pg_temp.p7_jwt(p_uid uuid)
returns void
language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p7_err_code(p_sqlerrm text)
returns text
language plpgsql as $$
declare
  v jsonb;
begin
  begin
    v := p_sqlerrm::jsonb;
    return v->>'code';
  exception when others then
    if p_sqlerrm like '%PRODUCT_INACTIVE%' then return 'PRODUCT_INACTIVE'; end if;
    if p_sqlerrm like '%INVALID_QUANTITY%' then return 'INVALID_QUANTITY'; end if;
    if p_sqlerrm like '%INVALID_UNIT%' then return 'INVALID_UNIT'; end if;
    if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
    if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
    if p_sqlerrm like '%ADJUSTMENT_NEGATIVE_RESULT%' then return 'ADJUSTMENT_NEGATIVE_RESULT'; end if;
    return p_sqlerrm;
  end;
end;
$$;

