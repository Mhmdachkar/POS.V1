create temporary table if not exists phase10_shift_results (
  seq      int generated by default as identity,
  test     text not null,
  expected text not null,
  actual   text not null,
  status   text not null check (status in ('PASS', 'FAIL', 'SKIP'))
);

create temporary table if not exists phase10_created (
  kind text not null,
  id   uuid not null
);

create or replace function pg_temp.p10_rec(
  p_test     text,
  p_expected text,
  p_actual   text,
  p_ok       boolean
) returns void
language plpgsql as $$
begin
  insert into phase10_shift_results (test, expected, actual, status)
  values (
    p_test, p_expected, p_actual,
    case when p_ok then 'PASS' else 'FAIL' end
  );
end;
$$;

create or replace function pg_temp.p10_skip(
  p_test     text,
  p_expected text,
  p_actual   text
) returns void
language plpgsql as $$
begin
  insert into phase10_shift_results (test, expected, actual, status)
  values (p_test, p_expected, p_actual, 'SKIP');
end;
$$;

create or replace function pg_temp.p10_jwt(p_uid uuid)
returns void
language plpgsql as $$
begin
  if p_uid is null then
    perform set_config('request.jwt.claims', '{}', false);
    perform set_config('request.jwt.sub', '', false);
  else
    perform set_config(
      'request.jwt.claims',
      json_build_object('sub', p_uid, 'role', 'authenticated')::text,
      false
    );
    perform set_config('request.jwt.sub', p_uid::text, false);
  end if;
end;
$$;

create or replace function pg_temp.p10_err_code(p_sqlerrm text)
returns text
language plpgsql as $$
declare
  v jsonb;
begin
  begin
    v := p_sqlerrm::jsonb;
    return v->>'code';
  exception when others then
    if p_sqlerrm like '%INVALID_AMOUNT%' then return 'INVALID_AMOUNT'; end if;
    if p_sqlerrm like '%INVALID_DEPOT%' then return 'INVALID_DEPOT'; end if;
    if p_sqlerrm like '%UNAUTHORIZED%' then return 'UNAUTHORIZED'; end if;
    if p_sqlerrm like '%SHIFT_NOT_OPEN%' then return 'SHIFT_NOT_OPEN'; end if;
    if p_sqlerrm like '%SHIFT_NOT_FOUND%' then return 'SHIFT_NOT_FOUND'; end if;
    return p_sqlerrm;
  end;
end;
$$;

create or replace function pg_temp.p10_cleanup_all()
returns void
language plpgsql as $$
declare
  v_prod uuid[];
  v_cust uuid[];
  v_sale uuid[];
  v_shift uuid[];
  v_ret uuid[];
  v_depot uuid[];
begin
  perform set_config('request.jwt.claims', '{}', false);
  perform set_config('request.jwt.sub', '', false);

  select coalesce(array_agg(id), array[]::uuid[]) into v_prod
  from public.products where name like 'PHASE10_TEST_%';

  select coalesce(array_agg(id), array[]::uuid[]) into v_cust
  from public.customers where name like 'PHASE10_TEST_%';

  select coalesce(array_agg(id), array[]::uuid[]) into v_sale
  from public.sales
  where customer_id = any(v_cust)
     or id in (select sale_id from public.sale_items where product_id = any(v_prod));

  select coalesce(array_agg(id), array[]::uuid[]) into v_ret
  from public.sale_returns
  where sale_id = any(v_sale)
     or shift_id in (select id from public.shifts where id in (select id from phase10_created where kind = 'shift'));

  select coalesce(array_agg(id), array[]::uuid[]) into v_shift
  from (
    select id from phase10_created where kind = 'shift'
    union
    select shift_id from public.sales where id = any(v_sale) and shift_id is not null
    union
    select shift_id from public.payments where customer_id = any(v_cust) and shift_id is not null
    union
    select shift_id from public.sale_returns where id = any(v_ret) and shift_id is not null
  ) s;

  select coalesce(array_agg(id), array[]::uuid[]) into v_depot
  from public.depots where code like 'P10T%';

  delete from public.sale_return_items where return_id = any(v_ret);
  delete from public.sale_returns where id = any(v_ret) or sale_id = any(v_sale);
  delete from public.payments
   where sale_id = any(v_sale) or customer_id = any(v_cust)
      or shift_id = any(v_shift);
  delete from public.inventory_transactions
   where product_id = any(v_prod) or reference_id = any(v_sale);
  delete from public.sale_items where sale_id = any(v_sale) or product_id = any(v_prod);
  delete from public.sales where id = any(v_sale);
  delete from public.audit_log
   where entity_id = any(v_shift)
      or entity_id = any(v_sale)
      or entity_id = any(v_cust)
      or entity_id = any(v_prod)
      or entity_id = any(v_ret);
  delete from public.shifts where id = any(v_shift);
  -- Orphan PHASE10-style opens left by a failed prior run (no txs, recent).
  delete from public.shifts s
   where s.opened_at > now() - interval '6 hours'
     and s.cashier_id in (
       '00000000-0000-0000-0000-000000000001',
       '00000000-0000-0000-0000-000000000002'
     )
     and s.opening_float_cfa in (0, 100, 250, 500, 1000, 4000)
     and not exists (select 1 from public.sales sl where sl.shift_id = s.id)
     and not exists (select 1 from public.payments p where p.shift_id = s.id)
     and not exists (select 1 from public.sale_returns r where r.shift_id = s.id);
  delete from public.customers where id = any(v_cust);
  delete from public.product_units where product_id = any(v_prod);
  delete from public.stock_entries where product_id = any(v_prod);
  delete from public.products where id = any(v_prod);
  delete from public.depots where id = any(v_depot);
  delete from phase10_created;
end;
$$;

