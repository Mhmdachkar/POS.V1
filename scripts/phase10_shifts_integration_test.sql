    'P10-D06 customer payment counted',
    'expected=50',
    v_result->>'expected_cash_cfa',
    (v_result->>'expected_cash_cfa')::numeric = 50
      and (v_result->'breakdown'->>'customer_pmts_cfa')::numeric = 50
